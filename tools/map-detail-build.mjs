#!/usr/bin/env node
// tools/map-detail-build.mjs — the map detail tiles and their 720p fallbacks,
// from the painted maps under art/environments/.
//
//   npm install --no-save sharp            (once; node_modules/ is ignored)
//   ASHENSPIRE_DIR=/path/to/AshenSpire node tools/map-detail-build.mjs
//   Add --fallback-only to refresh base maps without changing tiles or MAP_ART.
//
// Moved from cehinds/AshenSpire (docs/EXTERNAL-ASSETS-PLAN.md step 9). It writes:
//
//   common/map-detail/<hash>/<edge>/<x>-<y>.webp   the native-resolution pyramid
//                                                  (the `common` pack's map-detail/)
//   hd/assets/environments/<id>.webp               the up-to-720p fallback each tier
//                                                  starts from (then run
//                                                  tools/mobile-art.mjs for its twin)
//   dist/mapArt.generated.js                       the game's MAP_ART table, which
//                                                  names each map's tile hash and
//                                                  levels. It belongs to the game:
//                                                  copy it to AshenSpire's
//                                                  src/content/mapArt.generated.js
//                                                  in the PR that pins this release.
//
// The tile policy (levels, tile size) is the game's, read from
// src/content/mapPresentation.js in an AshenSpire checkout (tools/game.mjs).
// A tile folder is named by a hash of its source painting and the policy, so a
// new painting lands in a new folder; remove the old folder in the same PR.
// Then run node tools/manifest.mjs --write.
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gameModule } from './game.mjs';
import { policyFor, twinDimensions } from './mobileart-policy.mjs';

const { MAP_PRESENTATION: policy } = await import(gameModule('src/content/mapPresentation.js'));
const sharp = createRequire(import.meta.url)('sharp');
const root = fileURLToPath(new URL('../', import.meta.url));
const fallbackOnly = process.argv.includes('--fallback-only');
const sources = [
  ...['the-fractured-realm', 'the-shattered-gulf', 'the-fivefold-frontier'].map(id => [`${id}-world`, `worlds/${id}.png`]),
  ['fractured-realm-square', existsSync(resolve(root, 'art/environments/worlds/fractured-realm-square-detail.png')) ? 'worlds/fractured-realm-square-detail.png' : 'worlds/fractured-realm-square.png'],
  ...['ashen-crown', 'cinder-reach', 'drowned-coast', 'hollow-weald', 'pale-marches'].map(id => [`${id}-map`, `maps/${id}.png`]),
  ['crownfall-local', 'locations/crownfall-local.png'],
];
const maps = {};
for (const [id, source] of sources) {
  const input = readFileSync(resolve(root, 'art/environments', source));
  const metadata = await sharp(input).metadata();
  // Export from the original painting; never enlarge the previous 512px base.
  const fallback = twinDimensions(metadata, policyFor(`environments/${id}.webp`));
  await sharp(input).resize(fallback.width, fallback.height).webp({quality:90,effort:6})
    .toFile(resolve(root, `hd/assets/environments/${id}.webp`));
  if (fallbackOnly) {
    console.log(`${id}: fallback ${fallback.width}x${fallback.height}, tiles unchanged`);
    continue;
  }
  const longest = Math.max(metadata.width, metadata.height);
  const version = createHash('sha256').update(input).update(JSON.stringify(policy)).update('webp86-v1').digest('hex').slice(0, 16);
  const edges = [...new Set([...policy.levels.filter(n => n < longest), longest])];
  const levels = [];
  for (const edge of edges) {
    const width = Math.round(metadata.width * edge / longest), height = Math.round(metadata.height * edge / longest);
    const pixels = await sharp(input).resize(width, height).png().toBuffer();
    const dir = resolve(root, 'common/map-detail', version, String(edge)); mkdirSync(dir, {recursive: true});
    for (let y = 0; y < height; y += policy.tileSize) for (let x = 0; x < width; x += policy.tileSize) {
      await sharp(pixels).extract({left:x, top:y, width:Math.min(policy.tileSize,width-x), height:Math.min(policy.tileSize,height-y)})
        .webp({quality:86, effort:6}).toFile(resolve(dir, `${x/policy.tileSize}-${y/policy.tileSize}.webp`));
    }
    levels.push({edge, width, height});
  }
  maps[`assets/environments/${id}.webp`] = {assetHash:version, levels};
  console.log(`${id}: ${levels.map(l=>l.edge).join('/')}px`);
}
if (!fallbackOnly) {
  const target = resolve(root, 'dist/mapArt.generated.js'); mkdirSync(dirname(target), {recursive:true});
  writeFileSync(target, '// Generated by tools/map-detail-build.mjs; tile coordinates are derived.\nexport const MAP_ART = '+JSON.stringify(maps,null,2)+';\n');
  console.log('map-detail-build: wrote dist/mapArt.generated.js — copy it to AshenSpire src/content/mapArt.generated.js with the pin');
}
